def translate(text: str, language: str) -> str:
    """Traduz somente textos pertencentes à interface; dados do usuário ficam intactos."""
    if language.casefold().startswith("english"):
        for prefix, translated_prefix in (
            ("Login concluído: ", "Signed in: "),
            ("v0.0.1 | Conectado", "v0.0.1 | Connected"),
            ("v0.0.1 | Desconectado", "v0.0.1 | Disconnected"),
            ("v0.0.1 | Modo offline", "v0.0.1 | Offline mode"),
            ("Nova versão de desenvolvimento disponível: ", "New development version available: "),
            ("O canal de desenvolvimento está atualizado (", "The development channel is up to date ("),
            ("Atualização ", "Update "),
        ):
            if text.startswith(prefix):
                translated = translated_prefix + text[len(prefix):]
                return (
                    translated.replace(" disponível.", " is available.")
                    .replace(" A versão não inclui um instalador verificável para download automático.", " This release has no verified installer for automatic download.")
                    .replace(" Instalador verificado; será aberto na próxima inicialização: ", " Verified installer will open on next startup: ")
                    .replace(" Instalador verificado salvo: ", " Verified installer saved: ")
                    .replace(". Ative 'Instalar ao reiniciar' para abri-lo na próxima inicialização.", ". Turn on 'Install on next startup' to launch it then.")
                )
        return PT_EN.get(text, text)
    if language.casefold().startswith("português"):
        reverse = {translated: original for original, translated in PT_EN.items()}
        return reverse.get(text, text)
    return text
